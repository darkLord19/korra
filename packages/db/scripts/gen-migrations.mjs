/* global console */
// Bundles migrations/*.sql into src/migrations.generated.ts so the browser can migrate without fs.
// Run: pnpm --filter @korra/db db:bundle-migrations   (a test checks the output is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "migrations/meta/_journal.json"), "utf8"));
const migrations = journal.entries.map((e) => ({
  tag: e.tag,
  when: e.when,
  statements: readFileSync(join(root, "migrations", `${e.tag}.sql`), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));
const out =
  "// GENERATED by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.\n" +
  'import type { BundledMigration } from "./browser-migrate";\n\n' +
  `export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(join(root, "src/migrations.generated.ts"), out);
console.log(`bundled ${migrations.length} migrations`);
